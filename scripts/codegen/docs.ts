/**
 * API reference rendering for `docs/api-reference/`, emitted by the codegen driver from the
 * same in-memory model as `src/generated/`, so the docs can't drift from the code.
 *
 * Only short, factual data is copied from the OpenAPI documents (titles and one-line
 * operation summaries); descriptions and example payloads stay upstream and are linked.
 */
import { DEFAULT_SERVER } from '../../src/core/url.js'
import type { GeneratedParam } from './operation.js'

export const PORTAL_BASE = 'https://developers.vtex.com/docs/api-reference'

/**
 * Developer-portal slugs that differ from the slug derived from the file name, checked
 * against developers.vtex.com (`npm run check-doc-links`). `null`: the portal has no page.
 */
export const PORTAL_SLUG_OVERRIDES: Readonly<Record<string, string | null>> = Object.freeze({
  'VTEX - Ads API.json': 'vtex-ads-api',
  'VTEX - Antifraud Provider API.json': 'antifraud-provider-protocol',
  'VTEX - B2B Addresses API.json': 'b2b-addresses',
  'VTEX - Data Subject Rights.json': 'data-subject-rights-api',
  'VTEX - MasterData API - v10.2.json': 'masterdata-api',
  'VTEX - Pick and Pack Last Mile Protocol API.json': 'pick-and-pack-protocol-api',
  'VTEX - Promotions & Taxes API - v2.json': 'promotions-and-taxes-api-v2',
  'VTEX - Promotions & Taxes API.json': 'promotions-and-taxes-api',
  'VTEX - Shopee Integration API.json': 'vtex-shopee-integration-api',
  'VTEX - Bulk Pricing API.json': null,
  'VTEX - Marketplace APIs - Sent Offers.json': null,
  'VTEX - Marketplace Protocol - External Seller Marketplace.json': null,
  'VTEX - Tracking.json': null,
})

/** Developer-portal page for a schema file, or undefined when VTEX has none. */
export function portalUrl(file: string): string | undefined {
  if (Object.hasOwn(PORTAL_SLUG_OVERRIDES, file)) {
    const slug = PORTAL_SLUG_OVERRIDES[file]
    return slug === null ? undefined : `${PORTAL_BASE}/${slug}`
  }
  const slug = file
    .replace(/\.json$/, '')
    .replace(/^VTEX\s*-\s*/, '')
    .toLowerCase()
    .replace(/&/g, ' ')
    .replace(/[^a-z0-9.]+/g, '-')
    .replace(/^-|-$/g, '')
  return `${PORTAL_BASE}/${slug}`
}

export interface DocOperation {
  ns: string
  name: string
  httpMethod: string
  path: string
  /** Normalized server template; DEFAULT_SERVER for the account host. */
  server: string
  summary: string
  deprecated: boolean
  params: GeneratedParam[]
}

export interface DocApi {
  title: string
  file: string
  slug: string
  /** Field on `vtex.raw`; undefined when no operation is callable (types only). */
  rawNs?: string
  typesNs: string
  operations: DocOperation[]
  excludedCount: number
}

export interface DocSource {
  repo: string
  ref: string
}

const HEADER = '<!-- Generated by `npm run codegen` from the pinned VTEX OpenAPI documents. Do not edit by hand. -->'

/** Collapses whitespace and escapes Markdown/HTML so upstream text renders as plain text. */
export function plain(text: unknown, max = 160): string {
  const s = typeof text === 'string' ? text.replace(/\s+/g, ' ').trim() : ''
  const cut = s.length > max ? `${s.slice(0, max - 1).trimEnd()}…` : s
  return cut.replace(/[\\`*_{}[\]<>|#]/g, (c) => `\\${c}`)
}

/** Inline code span that stays valid whatever the content. */
export function code(text: string): string {
  const clean = text.replace(/[\r\n|]+/g, ' ')
  return clean.includes('`') ? `\`\` ${clean} \`\`` : `\`${clean}\``
}

const IDENT_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/

function key(name: string): string {
  return IDENT_RE.test(name) ? name : `'${name.replace(/[\\']/g, '\\$&')}'`
}

/** `ns.method({ a, b, 'x-y': … })` with the required option keys only. */
export function callSignature(op: DocOperation): string {
  const required = op.params.filter((p) => p.required)
  const args = required.length
    ? `{ ${required.map((p) => (IDENT_RE.test(p.name) ? p.name : `${key(p.name)}: …`)).join(', ')} }`
    : ''
  return `${op.ns}.${op.name}(${args})`
}

function splitServer(server: string): { origin: string; basePath: string } {
  const m = /^(https:\/\/[^/]+)(.*)$/.exec(server)
  return m ? { origin: m[1], basePath: m[2] } : { origin: server, basePath: '' }
}

function hostLabel(server: string): string {
  const { origin } = splitServer(server)
  return origin === splitServer(DEFAULT_SERVER).origin ? `${code(origin)} (account host)` : code(origin)
}

function schemaUrl(src: DocSource, file: string): string {
  return `https://github.com/${src.repo}/blob/${src.ref}/${encodeURIComponent(file)}`
}

export function renderApiDoc(api: DocApi, src: DocSource): string {
  const portal = portalUrl(api.file)
  const origins = [...new Set(api.operations.map((o) => splitServer(o.server).origin))]
  const multiHost = origins.length > 1
  const lines: string[] = [HEADER, '', `# ${plain(api.title, 200)}`, '']

  lines.push('| | |', '|---|---|')
  lines.push(`| SDK namespace | ${api.rawNs ? code(`vtex.raw.${api.rawNs}`) : 'none: types only (see below)'} |`)
  lines.push(`| Types | ${code(`import type { ${api.typesNs} } from 'vtex-sdk'`)} |`)
  lines.push(
    `| Operations | ${api.operations.length} callable` +
      (api.excludedCount ? `, ${api.excludedCount} not callable (non-VTEX or variable host)` : '') +
      ' |',
  )
  lines.push(`| Hosts | ${[...new Set(api.operations.map((o) => hostLabel(o.server)))].join('<br>') || 'none'} |`)
  lines.push(`| Official reference | ${portal ? `[developers.vtex.com](${portal})` : `not on the developer portal ([index](${PORTAL_BASE}))`} |`)
  lines.push(`| OpenAPI document | [${plain(api.file, 200)}](${schemaUrl(src, api.file)}) at ${code(src.ref.slice(0, 7))} |`)
  lines.push('')

  if (!api.rawNs) {
    lines.push(
      'No operation of this API is served by an allowlisted VTEX host, so it is not callable through `vtex.raw`.',
      'Typical reasons: it is a protocol that *you* implement (VTEX calls your service), or it runs on third-party hosts.',
      `Use the exported types (${code(api.typesNs)}) to type your own implementation or client.`,
      '',
    )
    return lines.join('\n')
  }

  lines.push(
    'Every method takes `(params, opts?)`: `params` holds path, query and header parameters plus `body`, and',
    '`opts` is the per-call `CallOptions` (`signal`, `timeoutMs`, `retry`, `idempotent`, `headers`).',
    'The call column lists the required keys; optional keys are in the last column.',
    '',
  )

  const byNs = new Map<string, DocOperation[]>()
  for (const op of api.operations) {
    if (!byNs.has(op.ns)) byNs.set(op.ns, [])
    byNs.get(op.ns)!.push(op)
  }
  for (const [ns, ops] of byNs) {
    lines.push(`## ${code(ns)}`, '')
    lines.push(multiHost ? '| Call | HTTP | Host | Summary | Optional |' : '| Call | HTTP | Summary | Optional |')
    lines.push(multiHost ? '|---|---|---|---|---|' : '|---|---|---|---|')
    for (const op of ops) {
      const { origin, basePath } = splitServer(op.server)
      const http = code(`${op.httpMethod.toUpperCase()} ${basePath}${op.path}`)
      const summary = (op.deprecated ? '**Deprecated.** ' : '') + plain(op.summary)
      const optional = op.params.filter((p) => !p.required).map((p) => code(p.name)).join(', ')
      const cells = [code(callSignature(op)), http, ...(multiHost ? [code(origin)] : []), summary, optional]
      lines.push(`| ${cells.join(' | ')} |`)
    }
    lines.push('')
  }
  return lines.join('\n')
}

export function renderIndex(apis: DocApi[], src: DocSource): string {
  const callable = apis.filter((a) => a.rawNs)
  const typesOnly = apis.filter((a) => !a.rawNs)
  const total = callable.reduce((n, a) => n + a.operations.length, 0)
  const lines: string[] = [
    HEADER,
    '',
    '# VTEX API reference (vtex-sdk)',
    '',
    `${callable.length} APIs and ${total} operations are callable through \`vtex.raw\`; ${typesOnly.length} more export types only.`,
    `Generated from [${src.repo}](https://github.com/${src.repo}/tree/${src.ref}) at ${code(src.ref.slice(0, 7))}.`,
    '',
    'Start with the [guides](../guides/README.md) for worked examples and the facades.',
    'To find an operation, search this folder for the HTTP path or a word from the summary, e.g.',
    '`grep -ri "orders/{orderId}" docs/api-reference`.',
    '',
    '## Callable APIs',
    '',
    '| API | SDK namespace | Operations | Official reference |',
    '|---|---|---|---|',
  ]
  for (const a of callable) {
    const portal = portalUrl(a.file)
    lines.push(
      `| [${plain(a.title, 120)}](./${a.slug}.md) | ${code(`vtex.raw.${a.rawNs}`)} | ${a.operations.length} | ` +
        `${portal ? `[portal](${portal})` : '—'} |`,
    )
  }
  lines.push('', '## Types only', '', 'Protocols you implement, or APIs on hosts outside the allowlist. Their types are exported.', '')
  lines.push('| API | Types | Official reference |', '|---|---|---|')
  for (const a of typesOnly) {
    const portal = portalUrl(a.file)
    lines.push(`| [${plain(a.title, 120)}](./${a.slug}.md) | ${code(a.typesNs)} | ${portal ? `[portal](${portal})` : '—'} |`)
  }
  lines.push('')
  return lines.join('\n')
}
